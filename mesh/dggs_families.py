"""
dggs_families.py
----------------
Discrete-global-grid (DGGS) meshes for FloodA5 (WP3 part 3, 2026-11 —
docs/notes/MeshFamilies_DGGS_Plan_2026-11.md). Writes FloodA5 GeoParquet
meshes in the same format as A5 and mesh/mesh_families.py meshes (the mesh
contract, docs/MESHES.md), which load with `--meshload`:

    h3        Uber H3 hexagons (aperture 7; not equal-area; 12 pentagons on
              the globe)                                        library: h3
    igeo7     ISEA7H with Z7 indexing (IGEO7): equal-area hexagons,
              aperture 7                                        library: dggal
    isea3h    ISEA3H: equal-area hexagons, aperture 3          library: dggal
    healpix   HEALPix (nested, equal-area on the WGS84 authalic sphere),
              quadrilaterals, aperture 4                        library: dggal
    rhealpix  rHEALPix: equal-area quadrilaterals, aperture 9  library: dggal

A5 is generated by FloodModel.jl --meshgen (mesh/a5_bridge.py), Cartesian
by --meshgen-cartesian, other polygon meshes by mesh/mesh_families.py.

Cells: every cell of the chosen level whose polygon intersects the AOI
(the rule A5 uses: pya5 "overlapping" containment). Polygons are the
library's corner vertices only (no densified edges: a face is one straight
side between two corners; at flood-model cell sizes the curvature of a
DGGS edge is far below a millimetre). Copies of one vertex that differ by
round-off between neighbouring cells (up to ~3e-14 degrees in DGGAL) are
snapped to a single copy, so a shared corner is bitwise identical in every
cell that has it. Adjacency is computed from shared edges and checked
against the library's own neighbour list; the two must agree exactly.

Cell IDs are the library's 64-bit cell index as 16 hex digits (H3's
15-character strings zero-padded). `resolution` is the DGGS level. The
schema metadata records the id scheme (= family name), the library and its
version, level, refinement ratio and whether the grid is equal-area.

Level: --res N, or --target-dx M (the level whose cell area at the AOI centre
is closest to M², in log terms). --list-levels prints the levels with their
cell size at the AOI centre and the expected number of cells.

Usage (with the Python that FloodA5 uses — Julia's Conda.jl Python, with its
Library\\bin on PATH; from Julia: A5Grid.PYTHON_CMD[]):
    python mesh/dggs_families.py igeo7    --aoi AOI.geojson --target-dx 25 --out mesh.parquet
    python mesh/dggs_families.py healpix  --bbox LON0,LAT0,LON1,LAT1 --res 18 --out m.parquet
    python mesh/dggs_families.py h3       --aoi AOI.geojson --list-levels
Prints one JSON line with a summary (or {"error": ...} and exit status 1).

Libraries: h3 (pip install h3) and DGGAL (pip install dggal==0.0.6). DGGAL
0.0.7's Windows wheel loads two copies of its eC runtime (ecrt.dll and the
renamed ecrt-<hash>.dll) and crashes in pydggal_setup; 0.0.6 does not.
Not supported: AOIs crossing the antimeridian or containing a pole.
"""

import argparse
import json
import math
import os
import sys
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

_R = 6_371_000.0          # FloodA5's Earth radius (A5Grid._EARTH_R, analysis R_EARTH)
SNAP_TOL_DEG = 1e-9       # vertex snapping tolerance (≈ 0.1 mm)


# ── Families ────────────────────────────────────────────────────────────────

FAMILIES = {
    #             library  DGGAL class   aperture equal-area  interior valence
    "h3":       ("h3",    None,         7,       False,      6),
    "igeo7":    ("dggal", "ISEA7H_Z7",  7,       True,       6),
    "isea3h":   ("dggal", "ISEA3H",     3,       True,       6),
    "healpix":  ("dggal", "HEALPix",    4,       True,       4),
    "rhealpix": ("dggal", "rHEALPix",   9,       True,       4),
}


def _version(dist):
    from importlib.metadata import version
    try:
        return version(dist)
    except Exception:
        return "unknown"


class H3Grid:
    """H3 through the `h3` package (v4 API). Cells are H3 index strings."""

    def __init__(self):
        import h3
        self.h3 = h3
        self.library = f"h3 {_version('h3')}"
        self.max_level = 15

    def cell_at(self, lon, lat, level):
        return self.h3.latlng_to_cell(lat, lon, level)

    def area_m2(self, c):
        return float(self.h3.cell_area(c, "m^2"))

    def candidates(self, level, lon0, lat0, lon1, lat1):
        poly = self.h3.LatLngPoly([(lat0, lon0), (lat0, lon1), (lat1, lon1), (lat1, lon0)])
        return list(self.h3.polygon_to_cells(poly, level))

    def corners(self, c):
        return [(float(lon), float(lat)) for lat, lon in self.h3.cell_to_boundary(c)]

    def centre(self, c):
        lat, lon = self.h3.cell_to_latlng(c)
        return float(lon), float(lat)

    def neighbours(self, c):
        return set(self.h3.grid_ring(c, 1))

    def int_id(self, c):
        return int(c, 16)

    def is_pentagon(self, c):
        return bool(self.h3.is_pentagon(c))


_DGGAL_APP = None


def _dggal():
    """Import DGGAL and run its one-time setup (once per process)."""
    global _DGGAL_APP
    if sys.platform.startswith("win") and _version("dggal") == "0.0.7":
        raise RuntimeError("dggal 0.0.7's Windows wheel crashes on setup (two copies of its "
                           "eC runtime); install 0.0.6:  pip install dggal==0.0.6 ecrt==0.0.6")
    import dggal
    if _DGGAL_APP is None:
        _DGGAL_APP = dggal.Application(appGlobals=vars(dggal))
        dggal.pydggal_setup(_DGGAL_APP)
    return dggal


class DGGALGrid:
    """A DGGAL DGGRS (ISEA7H_Z7, ISEA3H, HEALPix, rHEALPix). Cells are 64-bit ints."""

    def __init__(self, cls, valence):
        self.dg = _dggal()
        self.valence = valence
        self.d = getattr(self.dg, cls)()
        self.library = f"dggal {_version('dggal')} ({cls})"
        self.max_level = int(self.d.getMaxDGGRSZoneLevel())

    def cell_at(self, lon, lat, level):
        return int(self.d.getZoneFromWGS84Centroid(level, self.dg.GeoPoint(lat, lon)))

    def area_m2(self, c):
        return float(self.d.getZoneArea(c))

    def candidates(self, level, lon0, lat0, lon1, lat1):
        bb = self.dg.GeoExtent()
        bb.ll = self.dg.GeoPoint(lat0, lon0)
        bb.ur = self.dg.GeoPoint(lat1, lon1)
        zs = self.d.listZones(level, bb)
        return [] if zs is None else [int(z) for z in zs]

    def corners(self, c):
        return [(float(p.lon), float(p.lat)) for p in self.d.getZoneWGS84Vertices(c)]

    def centre(self, c):
        p = self.d.getZoneWGS84Centroid(c)
        return float(p.lon), float(p.lat)

    def neighbours(self, c):
        nbt = self.dg.Array("<int>")
        return {int(z) for z in self.d.getZoneNeighbors(c, nbt)}

    def int_id(self, c):
        return int(c)

    def is_pentagon(self, c):
        return self.valence == 6 and int(self.d.countZoneEdges(c)) == 5


def make_grid(family):
    lib, cls, _, _, valence = FAMILIES[family]
    return H3Grid() if lib == "h3" else DGGALGrid(cls, valence)


# ── Geometry helpers ────────────────────────────────────────────────────────

def polygon_area_m2(ring):
    """Plan area of a (lon, lat) ring as FloodA5 computes it
    (A5Grid._polygon_area_m2 / FA.polygon_area_m2: shoelace on an
    equirectangular projection about the mean vertex latitude; `ring` closed)."""
    lat0 = sum(v[1] for v in ring) / len(ring)
    k = math.cos(math.radians(lat0))
    a = 0.0
    n = len(ring)
    for i in range(n):
        xi, yi = math.radians(ring[i][0]) * _R * k, math.radians(ring[i][1]) * _R
        xj, yj = math.radians(ring[i - 1][0]) * _R * k, math.radians(ring[i - 1][1]) * _R
        a += (xj + xi) * (yj - yi)
    return abs(a) / 2.0


class VertexSnapper:
    """One canonical copy per vertex: points within `tol` (both coordinates) of
    an earlier point are replaced by it. Bucketed on a `tol` grid with the
    3 × 3 neighbouring buckets searched, so copies straddling a bucket
    boundary still merge (plain rounding would split them)."""

    def __init__(self, tol=SNAP_TOL_DEG):
        self.tol = tol
        self.buckets = defaultdict(list)
        self.merged = 0

    def __call__(self, v):
        x, y = v
        bx, by = math.floor(x / self.tol), math.floor(y / self.tol)
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for p in self.buckets.get((bx + dx, by + dy), ()):
                    if abs(p[0] - x) <= self.tol and abs(p[1] - y) <= self.tol:
                        if p != (x, y):
                            self.merged += 1
                        return p
        p = (float(x), float(y))
        self.buckets[(bx, by)].append(p)
        return p


def _dedupe(ring):
    out = []
    for v in ring:
        if not out or v != out[-1]:
            out.append(v)
    if len(out) > 1 and out[0] == out[-1]:
        out.pop()
    return out


def _orient_ccw(ring):
    a = sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1]))
    return ring if a > 0 else ring[::-1]


def shared_edge_adjacency(rings):
    """Neighbours = cells sharing a polygon side (identical vertex pair, after
    snapping). Returns (neighbour index lists, number of vertices shared by
    each neighbouring pair)."""
    side_cells = defaultdict(list)
    vert_cells = defaultdict(set)
    for i, ring in enumerate(rings):
        for a, b in zip(ring, ring[1:] + ring[:1]):
            side_cells[(min(a, b), max(a, b))].append(i)
        for v in ring:
            vert_cells[v].add(i)
    nbrs = [set() for _ in rings]
    for side, cells in side_cells.items():
        if len(cells) > 2:
            raise ValueError(f"a side is shared by {len(cells)} cells")
        if len(cells) == 2:
            i, j = cells
            nbrs[i].add(j); nbrs[j].add(i)
    shared = {}
    for i, ns in enumerate(nbrs):
        vi = set(rings[i])
        for j in ns:
            if i < j:
                shared[(i, j)] = len(vi & set(rings[j]))
    return [sorted(s) for s in nbrs], shared


# ── AOI ─────────────────────────────────────────────────────────────────────

def load_aoi(args):
    """(shapely geometry, (lon0, lat0, lon1, lat1)) of --aoi or --bbox."""
    import shapely
    if args.bbox:
        lon0, lat0, lon1, lat1 = (float(v) for v in args.bbox.split(","))
        geom = shapely.box(lon0, lat0, lon1, lat1)
    else:
        with open(args.aoi, "r", encoding="utf-8") as f:
            gj = json.load(f)
        geoms = ([shapely.geometry.shape(ft["geometry"]) for ft in gj["features"]]
                 if gj.get("type") == "FeatureCollection" else
                 [shapely.geometry.shape(gj.get("geometry", gj))])
        geom = shapely.union_all(geoms)
    lon0, lat0, lon1, lat1 = geom.bounds
    if lon1 - lon0 > 180 or lon0 < -180 or lon1 > 180:
        raise ValueError("AOIs crossing the antimeridian are not supported")
    if lat0 <= -89 or lat1 >= 89:
        raise ValueError("AOIs reaching a pole are not supported")
    return geom, (lon0, lat0, lon1, lat1)


def level_table(grid, bounds, aoi_area_m2):
    """Cell area at the AOI centre for every level (coarse levels skipped)."""
    lon = 0.5 * (bounds[0] + bounds[2]); lat = 0.5 * (bounds[1] + bounds[3])
    rows = []
    for lev in range(grid.max_level + 1):
        a = grid.area_m2(grid.cell_at(lon, lat, lev))
        if a < 1e10:
            rows.append({"level": lev, "cell_area_m2": a, "cell_size_m": math.sqrt(a),
                         "est_cells": int(round(aoi_area_m2 / a))})
    return rows


def choose_level(grid, bounds, target_dx):
    lon = 0.5 * (bounds[0] + bounds[2]); lat = 0.5 * (bounds[1] + bounds[3])
    best = None
    for lev in range(grid.max_level + 1):
        a = grid.area_m2(grid.cell_at(lon, lat, lev))
        err = abs(math.log(a / target_dx ** 2))
        if best is None or err < best[0]:
            best = (err, lev)
    return best[1]


# ── Mesh ────────────────────────────────────────────────────────────────────

def build_mesh(family, aoi, bounds, level):
    """Cells of `family` at `level` intersecting `aoi` → (cells, summary)."""
    import shapely
    grid = make_grid(family)
    if not 0 <= level <= grid.max_level:
        raise ValueError(f"{family}: level {level} outside 0..{grid.max_level}")
    lon0, lat0, lon1, lat1 = bounds
    latc = 0.5 * (lat0 + lat1)
    # Candidates: the bounding box grown by two cells, then the exact test.
    size_m = math.sqrt(grid.area_m2(grid.cell_at(0.5 * (lon0 + lon1), latc, level)))
    pad_lat = 2.0 * size_m / (math.radians(1.0) * _R)
    pad_lon = pad_lat / max(math.cos(math.radians(latc)), 1e-6)
    cand = grid.candidates(level, lon0 - pad_lon, lat0 - pad_lat, lon1 + pad_lon, lat1 + pad_lat)
    if not cand:
        raise ValueError(f"{family}: no cells listed at level {level}")
    corners = [grid.corners(c) for c in cand]
    polys = shapely.polygons([np.asarray(r + r[:1]) for r in corners])
    keep = np.flatnonzero(shapely.intersects(polys, aoi))
    if len(keep) == 0:
        raise ValueError(f"{family}: no cell at level {level} intersects the AOI")
    order = sorted(keep, key=lambda k: grid.int_id(cand[k]))
    cells_h = [cand[k] for k in order]
    raw = [corners[k] for k in order]

    snap = VertexSnapper()
    rings = [_orient_ccw(_dedupe([snap(v) for v in r])) for r in raw]
    nbr_idx, shared = shared_edge_adjacency(rings)
    split = [p for p, s in shared.items() if s != 2]
    if split:
        i, j = split[0]
        raise ValueError(f"{family}: {len(split)} neighbouring pairs share {shared[split[0]]} "
                         f"vertices, not 2 (e.g. cells {grid.int_id(cells_h[i]):016x}, "
                         f"{grid.int_id(cells_h[j]):016x}) — a face split by an extra vertex "
                         "(H3 near an icosahedron edge?); choose another AOI or level")

    # Check the adjacency against the library's own neighbour lists.
    pos = {c: k for k, c in enumerate(cells_h)}
    mismatches = 0
    for k, c in enumerate(cells_h):
        lib = {pos[n] for n in grid.neighbours(c) if n in pos}
        if lib != set(nbr_idx[k]):
            mismatches += 1
    if mismatches:
        raise ValueError(f"{family}: shared-edge adjacency differs from the library's "
                         f"neighbour lists for {mismatches} cells")

    ids = [f"{grid.int_id(c):016x}" for c in cells_h]
    cells = []
    lib_area = []
    for k, c in enumerate(cells_h):
        ring = rings[k]
        closed = [list(v) for v in ring] + [list(ring[0])]
        clon, clat = grid.centre(c)
        cells.append({
            "cell_id": ids[k], "resolution": int(level),
            "center_lon": clon, "center_lat": clat,
            "boundary": closed,
            "neighbours": [ids[j] for j in nbr_idx[k]],
            "cell_area": polygon_area_m2(closed),
        })
        lib_area.append(grid.area_m2(c))
    nbr_count = [len(n) for n in nbr_idx]
    lib_, cls, ratio, equal_area, valence = FAMILIES[family]
    summary = {
        "family": family, "library": grid.library, "level": int(level),
        "cells": len(cells), "candidates": len(cand),
        "valence_histogram": np.bincount(nbr_count).tolist(),
        "max_neighbours": int(max(nbr_count)),
        "corner_histogram": np.bincount([len(r) for r in rings]).tolist(),
        "mean_area_m2": float(np.mean([c["cell_area"] for c in cells])),
        "mean_library_area_m2": float(np.mean(lib_area)),
        "snapped_vertex_copies": snap.merged,
        "pentagons": int(sum(1 for c in cells_h if grid.is_pentagon(c))),
        "adjacency_checked": True,
    }
    md = {"mesh_family": family, "dggs_library": grid.library, "dggs_level": int(level),
          "dggs_refinement_ratio": ratio, "dggs_equal_area": equal_area,
          "dggs_system": cls or "H3", "dggs_interior_valence": valence}
    return cells, summary, md


def write(cells, out_path, family, md):
    import a5_bridge as bridge
    bridge.mesh_to_geoparquet(cells, out_path, id_scheme=family)
    bridge.write_id_scheme_metadata(out_path, family, **md)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("family", choices=sorted(FAMILIES))
    ap.add_argument("--aoi"); ap.add_argument("--bbox")
    ap.add_argument("--res", type=int)
    ap.add_argument("--target-dx", type=float)
    ap.add_argument("--list-levels", action="store_true")
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    try:
        if not (args.aoi or args.bbox):
            raise ValueError("give --aoi FILE or --bbox LON0,LAT0,LON1,LAT1")
        aoi, bounds = load_aoi(args)
        if args.list_levels:
            latc = 0.5 * (bounds[1] + bounds[3])
            area = aoi.area * (math.radians(1.0) * _R) ** 2 * math.cos(math.radians(latc))
            print(json.dumps({"family": args.family, "library": make_grid(args.family).library,
                              "levels": level_table(make_grid(args.family), bounds, area)}),
                  flush=True)
            return
        if not args.out:
            raise ValueError("give --out FILE")
        if (args.res is None) == (args.target_dx is None):
            raise ValueError("give exactly one of --res N or --target-dx METRES")
        level = args.res if args.res is not None else \
            choose_level(make_grid(args.family), bounds, args.target_dx)
        cells, summary, md = build_mesh(args.family, aoi, bounds, level)
        if args.target_dx is not None:
            md["target_dx_m"] = args.target_dx
        write(cells, args.out, args.family, md)
        summary.update(status="ok", output=args.out)
        print(json.dumps(summary), flush=True)
    except Exception as e:
        import traceback
        print(json.dumps({"error": f"{e}\n{traceback.format_exc()}"}), flush=True)
        sys.exit(1)


if __name__ == "__main__":
    main()
