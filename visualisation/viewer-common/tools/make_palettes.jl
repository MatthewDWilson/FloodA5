# tools/make_palettes.jl — regenerate visualisation/viewer-common/colormaps.json,
# the scientific colour maps of the globe viewers as fixed 256-entry tables.
#
#   julia --project=. visualisation/viewer-common/tools/make_palettes.jl [COLORSCHEMES_DIR]
#
# The tables come from the data files of ColorSchemes.jl (data/cmocean.jl,
# data/scicolor.jl), which is in the Manifest as a dependency of Makie; it is
# not loaded (no dependency is added): its data files are evaluated with a
# stand-in `RGB` and `loadcolorscheme`. COLORSCHEMES_DIR defaults to the
# package directory the active project resolves. Maps that do not have 256
# entries are resampled linearly in sRGB (as ColorSchemes' `get` does); the
# result is rounded to 8 bits. The licence texts are copied from the
# package's licence files, verbatim.

import TOML, JSON3

const CS_UUID = Base.UUID("35d6a980-a343-548e-a6ea-1d62b119f2f4")

const FAMILIES = [
    (id = "cmocean", file = "cmocean.jl", licence_file = "cmoceanlicense.txt",
     title = "cmocean",
     maps = ["deep", "dense", "turbid", "haline", "speed", "amp", "tempo", "thermal", "ice", "rain"],
     url = "https://matplotlib.org/cmocean/ (https://github.com/matplotlib/cmocean)",
     reference = "Thyng, K. M., Greene, C. A., Hetland, R. D., Zimmerle, H. M. and DiMarco, S. F. (2016). " *
                 "True colors of oceanography: guidelines for effective and accurate colormap selection. " *
                 "Oceanography 29(3), 9–13. doi:10.5670/oceanog.2016.66"),
    (id = "crameri", file = "scicolor.jl", licence_file = "scientificcolormaps.txt",
     title = "Scientific colour maps (Crameri)",
     maps = ["batlow", "oslo", "devon", "lajolla", "davos", "imola", "lapaz", "hawaii", "roma", "vik"],
     url = "http://www.fabiocrameri.ch/colourmaps.php",
     reference = "Crameri, F. (2018). Scientific colour-maps. Zenodo. doi:10.5281/zenodo.1243862"),
]

"A stand-in for ColorTypes' RGB: only what the data files construct."
module CSData
struct RGB{T}
    r::T
    g::T
    b::T
end
RGB(r, g, b) = RGB{Float64}(Float64(r), Float64(g), Float64(b))
const SCHEMES = Dict{Symbol,Vector{NTuple{3,Float64}}}()
loadcolorscheme(name, colors, cat = "", notes = "") =
    (SCHEMES[name] = [(Float64(c.r), Float64(c.g), Float64(c.b)) for c in colors]; nothing)
end

function colorschemes_dir()
    isempty(ARGS) || return ARGS[1]
    src = Base.locate_package(Base.PkgId(CS_UUID, "ColorSchemes"))
    src === nothing && error("ColorSchemes.jl not found from the active project: pass its directory")
    return dirname(dirname(src))
end

"`cols` resampled to n entries, linear in sRGB, rounded to 8 bits → 'rrggbb' × n."
function table_hex(cols::Vector{NTuple{3,Float64}}, n = 256)
    m = length(cols)
    io = IOBuffer()
    for i in 0:n-1
        x = m == n ? Float64(i) : i * (m - 1) / (n - 1)
        j = min(floor(Int, x), m - 2); u = x - j
        c = m == n ? cols[i+1] : ntuple(k -> cols[j+1][k] + (cols[j+2][k] - cols[j+1][k]) * u, 3)
        for k in 1:3
            print(io, string(round(Int, clamp(c[k], 0, 1) * 255), base = 16, pad = 2))
        end
    end
    return String(take!(io))
end

function main()
    dir = colorschemes_dir()
    proj = TOML.parsefile(joinpath(dir, "Project.toml"))
    proj["name"] == "ColorSchemes" || error("$dir is not ColorSchemes.jl")
    csver = proj["version"]
    families = Pair{String,Any}[]
    for f in FAMILIES
        path = joinpath(dir, "data", f.file)
        empty!(CSData.SCHEMES)
        Base.include(CSData, path)
        lic = read(joinpath(dir, "data", f.licence_file), String)
        lic = strip(replace(lic, "\r\n" => "\n"))
        copyright = something(match(r"Copyright \(c\)[^\n]*", lic), (match = "",)).match
        header = join(Iterators.takewhile(l -> startswith(l, "#"), eachline(path)), "\n")
        m = match(r"version\s+([0-9.]+)", header)
        version = m === nothing ?
            "not stated in ColorSchemes.jl $csver's data file" : String(m[1])
        maps = Pair{String,String}[]
        for name in f.maps
            cols = get(CSData.SCHEMES, Symbol(name), nothing)
            cols === nothing && error("$(f.id): no map $name in $path")
            length(cols) == 256 || @info "$(f.id) $name: $(length(cols)) entries, resampled to 256"
            push!(maps, name => table_hex(cols))
        end
        push!(families, f.id => (title = f.title, version = version, url = f.url, reference = f.reference,
                                 source = "ColorSchemes.jl $csver, data/$(f.file)",
                                 licence = "MIT", copyright = copyright, licence_text = lic,
                                 maps = (; (Symbol(k) => v for (k, v) in maps)...)))
    end
    doc = (_comment = "Generated by visualisation/viewer-common/tools/make_palettes.jl — do not edit. " *
                      "256-entry sRGB tables, 'rrggbb' × 256 per map (docs/DATA_FORMATS.md §6).",
           format = 1, generated_from = "ColorSchemes.jl $csver",
           families = (; (Symbol(k) => v for (k, v) in families)...))
    out = joinpath(@__DIR__, "..", "colormaps.json")
    open(out, "w") do io
        JSON3.pretty(io, JSON3.write(doc), JSON3.AlignmentContext(indent = 1))
        println(io)
    end
    println("wrote $(normpath(out)): ", join(("$(k) ($(length(FAMILIES[i].maps)))" for (i, (k, _)) in enumerate(families)), ", "),
            " from ColorSchemes.jl $csver")
end

main()
